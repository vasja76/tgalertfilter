async def check_health():
    """Проверяет, всё ли работает. Возвращает список проблем
    (пустой список — всё в порядке). Названия проблем попадают в пульс."""
    problems = []

    # 1. Telegram: реальный запрос к серверам, а не просто флаг подключения.
    try:
        if not client.is_connected():
            problems.append("Telegram")
        else:
            await asyncio.wait_for(client.get_me(), timeout=20)
    except Exception as e:
        print(f"Health: Telegram err: {e}", flush=True)
        problems.append("Telegram")

    # 2. База данных: смотрим итог ПОСЛЕДНЕГО реального обращения
    #    (старт, команды, суточный запрос). Сами в базу не ходим.
    #    Работа на запасном списке слов (USING_FALLBACK) тоже считается
    #    проблемой БД, даже если часть запросов проходит (например, в таблице
    #    не хватает колонки).
    if not DB_OK or USING_FALLBACK:
        problems.append("БД")

    # 3. Список слов не пуст (иначе уведомления не придут никогда).
    if not KEYWORDS:
        problems.append("нет слов")

    # 4. API тревог отвечает (проверяем, только если мониторинг включён).
    if monitoring_enabled() and time.time() - ALERTS_LAST_OK > 180:
        problems.append("тревоги")

    return problems


async def try_recover_from_db():
    """Пока бот работает на запасных данных (USING_FALLBACK), пробует прочитать
    слова и настройки из БД. Когда получилось, переходит на данные из БД."""
    global KEYWORDS
    global QUIET_KEYWORDS
    global STOP_WORDS
    global DISABLED_WORDS
    global BOT_SETTINGS
    global USING_FALLBACK

    keywords = await asyncio.to_thread(db_get_keywords)
    settings = await asyncio.to_thread(db_get_settings)
    if keywords is None or settings is None:
        return      # БД всё ещё недоступна, попробуем при следующей проверке

    KEYWORDS, QUIET_KEYWORDS, STOP_WORDS, DISABLED_WORDS = keywords
    BOT_SETTINGS = settings
    USING_FALLBACK = False
    print(f"БД снова доступна: загружено слов {len(KEYWORDS)}", flush=True)


async def heartbeat_loop():
    """Цикл пульса: проверка состояния раз в 5 минут, обновление
    сообщения при смене проблем и в любом случае раз в 10 минут (чтобы время
    менялось и было видно, что бот жив).
    Смена статуса тревог обновляет пульс отдельно (в alerts_monitoring_loop)."""
    global LAST_HEALTH_PROBLEMS

    # При запуске ждём первый опрос тревог (не дольше 30 секунд), чтобы
    # первое закреплённое сообщение сразу показало правильные значки.
    if monitoring_enabled():
        try:
            await asyncio.wait_for(ALERTS_FIRST_POLL_DONE.wait(), timeout=30)
        except asyncio.TimeoutError:
            pass

    last_problems = None        # какой список проблем показан сейчас
    checks_since_update = 0     # сколько проверок прошло с последнего обновления

    while True:
        # Если бот стартовал без БД, пробуем подключиться к ней заново.
        if USING_FALLBACK and supabase:
            await try_recover_from_db()

        problems = await check_health()
        LAST_HEALTH_PROBLEMS = problems     # запоминаем для цикла тревог и команд

        # Обновляем при смене проблем или каждую вторую проверку (= 10 минут).
        if problems != last_problems or checks_since_update >= 2:
            # Отправка идёт через requests: выносим из цикла событий.
            await asyncio.to_thread(update_heartbeat, problems)
            last_problems = problems
            checks_since_update = 0

        checks_since_update += 1
        await asyncio.sleep(300)


async def db_keepalive_loop():
    """Раз в сутки делает лёгкий запрос к Supabase, чтобы бесплатный проект
    не «заснул» из-за недели без активности."""
    # Первый запрос не нужен: при старте база уже читалась.
    while True:
        await asyncio.sleep(86400)
        await asyncio.to_thread(db_ping)


