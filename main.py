def strip_stop_words(text_lower):
    """Вырезает исключения (STOP_WORDS) из текста (он уже в нижнем регистре).

    Исключения заменяются пробелом, чтобы остатки по краям не склеились
    в новое слово. Длинные исключения вырезаются первыми. Исходный пост
    не меняется: это только копия для поиска ключевых слов."""
    for stop in sorted(STOP_WORDS, key=len, reverse=True):
        text_lower = text_lower.replace(stop, " ")
    return text_lower


@client.on(events.NewMessage(chats=TARGET_CHANNELS))
async def handle_new_message(event):
    """Срабатывает на каждый новый пост в каналах из TARGET_CHANNELS.
    Если в посте есть ключевое слово, присылает его в общий чат."""
    message_text = event.raw_text
    text_lower = message_text.lower()   # поиск не зависит от регистра

    # Все ключевые слова, найденные в посте ПОСЛЕ вырезания исключений.
    # В канал уходит исходный текст поста, а не вырезанная копия.
    searchable = strip_stop_words(text_lower)
    matched = [kw for kw in KEYWORDS if kw in searchable]
    if not matched:
        return

    # Определяем, как подписать канал: @username или название.
    chat = await client.get_entity(event.chat_id)
    username = (
        chat.username
        or (chat.usernames[0].username if getattr(chat, 'usernames', None) else None)
    )
    channel_id = f"@{username}" if username else getattr(chat, 'title', 'Канал')
    alert_msg = f"▶ {channel_id}\n{message_text}"

    # В тихом режиме без звука приходят только сообщения, где ВСЕ найденные
    # слова помечены 🔕. Если есть хотя бы одно обычное слово, сообщение
    # приходит со звуком.
    silent = silent_mode() and all(kw in QUIET_KEYWORDS for kw in matched)
    await notify(alert_msg, silent=silent)


