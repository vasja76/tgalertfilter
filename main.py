def word_kind(word):
    """Текущий тип слова в памяти: "stop", "quiet", "normal" или None (нет такого)."""
    if word in STOP_WORDS:
        return "stop"
    if word in QUIET_KEYWORDS:
        return "quiet"
    if word in KEYWORDS:
        return "normal"
    return None


async def cmd_add(arg, kind):
    """/add, /addsilent, /addstop — добавить слово или сменить его тип.

    arg  — текст после команды (само слово, возможно в кавычках);
    kind — нужный тип: "normal", "quiet" или "stop"."""
    word = parse_word(arg)
    if not word.strip():
        await reply("❌ Пустое слово")
        return

    current = word_kind(word)

    # Слово уже есть и такого же типа: менять нечего, в БД не ходим.
    if current == kind:
        await reply(f'ℹ️ Уже есть ({KIND_NAME[kind]}), без изменений: "{word}"')
        return

    if await asyncio.to_thread(db_add_keyword, word, kind):
        await refresh_keywords()
        # Новое слово или смена типа у существующего: тексты разные.
        table = NEW_REPLY if current is None else CHANGED_REPLY
        await reply(f'{table[kind]}: "{word}"')
    else:
        await reply("❌ Ошибка записи в БД")


async def cmd_del(text):
    """/del слово — удалить слово или исключение."""
    word = parse_word(text[5:])
    was_stop = word in STOP_WORDS       # запоминаем до удаления: нужно для ответа
    deleted = await asyncio.to_thread(db_del_keyword, word)
    if deleted is None:
        await reply("❌ Ошибка удаления из БД")
    elif deleted == 0:
        await reply(f'⚠️ Не найдено: "{word}"')
    else:
        await refresh_keywords()
        what = "исключение" if was_stop else "слово"
        await reply(f'🗑 Удалено {what}: "{word}"')


async def cmd_list():
    """/list — настройки и список слов (длинный список режется на части)."""
    header = (
        f"⚙️ Настройки:\nalerts = {setting('alerts')}\n"
        f"silent = {silent_description()}\n"
        f"2 ({second_name()}) = {second_description()}\n\n"
        f"🔑 Ключевые слова ({len(KEYWORDS)}):\n"
    )
    if QUIET_KEYWORDS:
        header += "(🔕 — без звука в тихом режиме)\n"

    # Слова показываем в кавычках, чтобы были видны пробелы по краям.
    lines = [f'• "{kw}"' + (" 🔕" if kw in QUIET_KEYWORDS else "") for kw in KEYWORDS]

    # Исключения показываем отдельным блоком.
    if STOP_WORDS:
        lines.append("")
        lines.append(f"🚫 Исключения ({len(STOP_WORDS)}):")
        lines += [f'• "{w}"' for w in STOP_WORDS]

    # Отключённые слова (начинаются с «#») тоже показываем, чтобы про них не забыть.
    if DISABLED_WORDS:
        lines.append("")
        lines.append(f"💤 Отключённые ({len(DISABLED_WORDS)}):")
        lines += [f'• "{w}"' for w in DISABLED_WORDS]

    # Лимит Telegram — 4096 символов на сообщение, поэтому режем на части.
    chunks = []
    current = header
    for line in lines:
        if len(current) + len(line) + 1 > 3800:
            chunks.append(current)
            current = ""
        current += line + "\n"
    chunks.append(current)

    for chunk in chunks:
        await reply(chunk)


