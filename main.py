def send_telegram_alert(text, silent=False, chat_id=None):
    """Отправляет сообщение от имени бота (синхронно).

    silent  — True: без звука (флаг disable_notification).
    chat_id — куда слать; по умолчанию в общий чат MY_TELEGRAM_ID.
    Ошибки только пишутся в лог: сбой отправки не должен останавливать бота.
    Из async-кода вызывайте notify(), а не эту функцию напрямую."""
    payload = {
        "chat_id": chat_id if chat_id is not None else MY_TELEGRAM_ID,
        "text": text[:MAX_MESSAGE_LEN],
    }
    if silent:
        payload["disable_notification"] = True
    try:
        res = bot_api("sendMessage", payload)
        if not res.get("ok"):
            print(f"Send fail: {res}", flush=True)
    except Exception as e:
        print(f"Send err: {e}", flush=True)


async def notify(text, silent=False, chat_id=None):
    """Асинхронная обёртка над send_telegram_alert.

    Отправка идёт в отдельном потоке: если у Telegram проблемы с сетью,
    ожидание до 10 секунд не замораживает остальной бот."""
    await asyncio.to_thread(send_telegram_alert, text, silent, chat_id)


