def kyiv_from_utc(utc):
    """Переводит время UTC в киевское с учётом летнего/зимнего времени.

    Переход происходит в последнее воскресенье марта и октября в 01:00 UTC.
    Летом киевское время = UTC+3, зимой = UTC+2."""
    def last_sunday(month):
        # Берём 31-е число (в марте и октябре оно есть) и отступаем назад
        # до воскресенья: weekday() у воскресенья = 6.
        d = datetime(utc.year, month, 31, 1, 0, tzinfo=timezone.utc)
        return d - timedelta(days=(d.weekday() + 1) % 7)

    summer = last_sunday(3) <= utc < last_sunday(10)
    return utc + timedelta(hours=3 if summer else 2)


def kyiv_now():
    """Текущее киевское время (для пульса и расписания тихого режима)."""
    return kyiv_from_utc(datetime.now(timezone.utc))


def _parse_clock(part):
    """Разбирает одну границу времени: '23', '6' или '06:30'.
    Возвращает минуты от полуночи или None, если формат неверный.
    Допускается '24' как конец суток."""
    m = re.fullmatch(r"(\d{1,2})(?::(\d{2}))?", part)
    if not m:
        return None
    hours = int(m.group(1))
    minutes = int(m.group(2) or 0)
    total = hours * 60 + minutes
    if minutes > 59 or total > 1440:
        return None
    return total


def parse_silent_window(text):
    """Разбирает окно тихого режима: '23-6', '23:00-06:00', '22:30-7'.

    Возвращает (начало, конец) в минутах от полуночи или None, если формат
    неверный. Длинные тире (– —) тоже принимаются: iPhone иногда
    подменяет ими обычный дефис."""
    t = text.replace("–", "-").replace("—", "-").replace(" ", "")
    parts = t.split("-")
    if len(parts) != 2:
        return None
    start = _parse_clock(parts[0])
    end = _parse_clock(parts[1])
    if start is None or end is None:
        return None
    # Начало не может быть 24:00, а одинаковые границы окна не задают.
    if start >= 1440 or start == end:
        return None
    return start, end


def format_window(window):
    """(1380, 360) -> '23:00-06:00' (так окно хранится в базе)."""
    return "-".join(f"{m // 60:02d}:{m % 60:02d}" for m in window)


def silent_mode(now=None):
    """True, если СЕЙЧАС сообщения должны приходить без звука.

    Учитывает настройку silent: on / off / окно времени.
    Параметр now нужен только для тестов (по умолчанию берётся текущее время)."""
    value = setting("silent")
    if value == "on":
        return True
    if value == "off":
        return False

    window = parse_silent_window(value)
    if window is None:
        # Непонятное значение (например, поправили в таблице вручную):
        # безопаснее, чтобы сообщения шли со звуком.
        return False

    start, end = window
    now = now or kyiv_now()
    minutes = now.hour * 60 + now.minute
    if start < end:
        return start <= minutes < end       # обычное окно, например 6-23
    return minutes >= start or minutes < end    # окно через полночь, например 23-6


def silent_description():
    """Текст о тихом режиме для /list и /silent, например:
    'off' или '23:00-06:00 (сейчас тихо)'."""
    value = setting("silent")
    if value in ("on", "off"):
        return value
    window = parse_silent_window(value)
    if window is None:
        return f"{value} (непонятное значение, считается off)"
    state = "тихо" if silent_mode() else "со звуком"
    return f"{format_window(window)} (сейчас {state})"


# ВЫХОДНЫЕ для режима /2 weekend: в это время второй район НЕ отслеживается
# (на выходных вы не на работе). Время киевское. Формат: (день недели, час),
# день недели как в weekday(): понедельник = 0, ... пятница = 4, воскресенье = 6.
WEEKEND_START = (4, 18)     # начало: пятница 18:00
WEEKEND_END = (0, 7)        # конец: понедельник 07:00

DAY_NAMES = ["пн", "вт", "ср", "чт", "пт", "сб", "вс"]


def in_weekend(now=None):
    """True, если сейчас выходные (от WEEKEND_START до WEEKEND_END по киевскому
    времени). Окно переходит через конец недели (пт 18:00 -> пн 07:00), поэтому
    время считается в минутах от понедельника 00:00."""
    now = now or kyiv_now()
    minute_of_week = now.weekday() * 1440 + now.hour * 60 + now.minute
    start = WEEKEND_START[0] * 1440 + WEEKEND_START[1] * 60
    end = WEEKEND_END[0] * 1440 + WEEKEND_END[1] * 60
    if start < end:
        return start <= minute_of_week < end
    return minute_of_week >= start or minute_of_week < end


def weekend_text():
    """Границы выходных текстом, например 'пт 18:00 - пн 07:00'."""
    return (f"{DAY_NAMES[WEEKEND_START[0]]} {WEEKEND_START[1]:02d}:00 - "
            f"{DAY_NAMES[WEEKEND_END[0]]} {WEEKEND_END[1]:02d}:00")


def second_name():
    """Название второго района (для сообщений и справки)."""
    return WATCHED_DISTRICTS[1]["name"] if len(WATCHED_DISTRICTS) > 1 else "второй район"


def second_active(now=None):
    """True, если второй район СЕЙЧАС отслеживается.

    Учитывает настройку second: on — всегда, off — никогда, weekend — везде,
    кроме выходных (см. in_weekend). Непонятное значение считается как on
    (безопаснее не пропустить тревогу). Параметр now нужен только для тестов."""
    if len(WATCHED_DISTRICTS) < 2:
        return False
    value = setting("second")
    if value == "off":
        return False
    if value == "weekend":
        return not in_weekend(now)
    return True


def active_districts():
    """Районы, которые отслеживаются сейчас: первый всегда, второй — по
    настройке second. Именно этот список используют опрос тревог, пульс и /now."""
    return WATCHED_DISTRICTS[:1] + (WATCHED_DISTRICTS[1:2] if second_active() else [])


def second_description():
    """Текст о втором районе для /list и /2, например 'on' или
    'weekend (сейчас не отслеживается)'."""
    value = setting("second")
    if value in ("on", "off"):
        return value
    if value == "weekend":
        state = "отслеживается" if second_active() else "не отслеживается"
        return f"weekend (сейчас {state})"
    return f"{value} (непонятное значение, считается on)"


