async def start_telethon():
    """Главная асинхронная функция: подключается к Telegram, запускает
    фоновые циклы и держит соединение."""
    global ADMIN_CHAT_ID
    global ALERTS_FIRST_POLL_DONE

    print(f"Запуск Telethon... Версия {VERSION}", flush=True)
    try:
        await client.start()                # вход по SESSION_STRING
        me = await client.get_me()
        ADMIN_CHAT_ID = me.id               # сюда будут уходить ответы на команды
        print(f"Вошли как: {me.first_name} (id={me.id})", flush=True)
        print(
            f"Настройки: {BOT_SETTINGS} | Ключевые слова из БД ({len(KEYWORDS)} шт.)",
            flush=True
        )
        if USING_FALLBACK:
            print("ВНИМАНИЕ: БД недоступна при запуске, работаем на запасном списке слов "
                  "(DEFAULT_KEYWORDS). Раз в 5 минут пробуем подключиться снова.", flush=True)
        if not KEYWORDS:
            print("ВНИМАНИЕ: список ключевых слов пуст — уведомления приходить не будут.", flush=True)

        # Событие должно быть создано до запуска циклов: пульс ждёт его.
        ALERTS_FIRST_POLL_DONE = asyncio.Event()

        # Фоновые циклы работают параллельно с обработчиками Telegram.
        asyncio.create_task(heartbeat_loop())       # пульс и проверка здоровья
        asyncio.create_task(alerts_monitoring_loop())   # опрос тревог
        asyncio.create_task(db_keepalive_loop())    # суточный запрос к БД

        # Остаёмся подключёнными, пока клиент не отключится.
        await client.run_until_disconnected()
    except Exception as e:
        print(f"Telethon err: {e}", flush=True)


if __name__ == "__main__":
    # Flask в отдельном потоке (daemon: закроется вместе с программой),
    # чтобы веб-сервер и Telegram-клиент работали одновременно.
    threading.Thread(target=run_flask, daemon=True).start()
    asyncio.run(start_telethon())
