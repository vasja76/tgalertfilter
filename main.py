# из них: «слово», „слово“, “слово”, "слово", 'слово'.
QUOTE_CHARS = "\"'«»“”„‟‘’‚"


def parse_word(arg):
    """Готовит слово из текста команды.

    Слово можно взять в кавычки (любые, см. QUOTE_CHARS), чтобы сохранить
    пробелы по краям:
        /add «на київ »
    Telegram сам обрезает пробелы в конце сообщения, поэтому без кавычек
    пробел в конце слова не сохранится.
    Результат всегда в нижнем регистре (текст постов тоже сравнивается так)."""
    if len(arg) >= 2 and arg[0] in QUOTE_CHARS and arg[-1] in QUOTE_CHARS:
        word = arg[1:-1]
    else:
        word = arg.strip()
    return word.lower()


